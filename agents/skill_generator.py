    @staticmethod
    def _allowed_tools_for_task(task_type: str) -> str:
        """Return the allowed-tools declaration appropriate for a task type."""
        # Code-centric tasks need write/execute access
        code_tasks = {
            "code_generation", "test_generation", "debugging",
            "refactoring", "performance_optimization",
        }
        if task_type in code_tasks:
            return "Bash Read Write Edit"

        # Security audits read code but may run scanners
        if task_type == "security_audit":
            return "Bash Read Grep Glob"

        # Read-only / text-output tasks
        return "Read Grep Glob WebFetch WebSearch"

